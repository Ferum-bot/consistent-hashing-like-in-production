package models

// WriteTicket выдаётся книгой на время записи по пользователю.
// Пока запись не закрыта, сверять этого пользователя нельзя.
type WriteTicket struct {
	UserID int64
	// Epoch — какая загрузка книги выдала билет. После перезагрузки старые билеты игнорируются.
	Epoch uint64
}

// Observation — состояние пользователя в книге перед чтением.
// Если после чтения оно изменилось, ответ сервиса сверять нельзя.
type Observation struct {
	UserID int64
	Epoch  uint64
	Seq    uint32
	// Busy — по пользователю идёт запись или результат прошлой записи неизвестен.
	Busy bool
}
